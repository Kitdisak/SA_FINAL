-- รันด้วย schema user ที่จะใช้กับแอป (สร้างตารางใหม่)
CREATE TABLE EVAL_ACCOUNTS (
  USERNAME VARCHAR2(50) PRIMARY KEY,
  DISPLAY_NAME VARCHAR2(200) NOT NULL,
  ROLE VARCHAR2(20) NOT NULL CHECK (ROLE IN ('evaluator','evaluatee')),
  POSITION_NAME VARCHAR2(200),
  PIN_HASH VARCHAR2(64) NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE EVAL_EVALUATIONS (
  EVALUATEE_ID VARCHAR2(50) PRIMARY KEY,
  EVALUATOR_ID VARCHAR2(50) NOT NULL,
  EVALUATOR_NAME VARCHAR2(200) NOT NULL,
  SCORES_JSON CLOB NOT NULL,
  CC_JSON CLOB,
  STRENGTHS CLOB,
  IMPROVEMENTS CLOB,
  STATUS VARCHAR2(20) NOT NULL CHECK (STATUS IN ('draft','submitted')),
  UPDATED_AT NUMBER(13) NOT NULL,
  SUBMITTED_AT NUMBER(13) DEFAULT 0 NOT NULL,
  ACK NUMBER(1) DEFAULT 0 NOT NULL CHECK (ACK IN (0,1)),
  ACK_AT NUMBER(13) DEFAULT 0 NOT NULL,
  REPLY CLOB,
  REPLY_AT NUMBER(13) DEFAULT 0 NOT NULL,
  CONSTRAINT FK_EVAL_EVALUATEE FOREIGN KEY (EVALUATEE_ID) REFERENCES EVAL_ACCOUNTS(USERNAME),
  CONSTRAINT FK_EVAL_EVALUATOR FOREIGN KEY (EVALUATOR_ID) REFERENCES EVAL_ACCOUNTS(USERNAME)
);
