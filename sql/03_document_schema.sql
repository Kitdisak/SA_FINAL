-- ---------- D1 ข้อมูลผู้ใช้งาน ----------
-- ตารางที่ 2 departments
CREATE TABLE departments (
  department_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  department_name  VARCHAR2(100 CHAR) NOT NULL UNIQUE
);

-- ตารางที่ 1 users  (คอลัมน์ตามเอกสาร + position_name, emp_code, phone, email, start_date สำหรับหน้าประวัติพนักงาน)
CREATE TABLE users (
  user_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username       VARCHAR2(50 CHAR)  NOT NULL UNIQUE,
  password_hash  VARCHAR2(255 CHAR) NOT NULL,
  full_name      VARCHAR2(150 CHAR) NOT NULL,
  role           VARCHAR2(20 CHAR)  NOT NULL CHECK (role IN ('employee', 'mentor', 'hr', 'executive')),
  department_id  NUMBER REFERENCES departments(department_id),
  status         VARCHAR2(20 CHAR)  DEFAULT 'active' NOT NULL CHECK (status IN ('active', 'inactive')),
  position_name  VARCHAR2(150 CHAR),
  emp_code       VARCHAR2(20 CHAR),
  phone          VARCHAR2(30 CHAR),
  email          VARCHAR2(150 CHAR),
  start_date     DATE
);

-- ตารางที่ 3 notifications  (+ detail สำหรับรายละเอียด)
CREATE TABLE notifications (
  notification_id  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id          NUMBER NOT NULL REFERENCES users(user_id),
  message          VARCHAR2(255 CHAR) NOT NULL,
  notify_type      VARCHAR2(30 CHAR),
  is_read          NUMBER(1) DEFAULT 0 NOT NULL CHECK (is_read IN (0, 1)),
  created_at       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  detail           VARCHAR2(1000 CHAR)
);
CREATE INDEX ix_notifications_user ON notifications (user_id, is_read);

-- ---------- D3 ข้อมูลการประเมิน ----------
-- ตารางที่ 5 evaluation_cycles
CREATE TABLE evaluation_cycles (
  cycle_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cycle_name  VARCHAR2(100 CHAR) NOT NULL,
  start_date  DATE NOT NULL,
  end_date    DATE NOT NULL,
  status      VARCHAR2(20 CHAR) DEFAULT 'draft' NOT NULL CHECK (status IN ('draft', 'open', 'closed')),
  min_goals   NUMBER(2) DEFAULT 1 NOT NULL,          -- จำนวนเป้าหมายขั้นต่ำก่อนส่ง (BR-EVAL-02)
  CONSTRAINT ck_cycle_dates CHECK (end_date >= start_date)
);

-- ตารางที่ 6 cycle_stages
CREATE TABLE cycle_stages (
  stage_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cycle_id    NUMBER NOT NULL REFERENCES evaluation_cycles(cycle_id),
  stage_name  VARCHAR2(50 CHAR) NOT NULL,
  start_date  DATE NOT NULL,
  end_date    DATE NOT NULL,
  stage_key   VARCHAR2(20 CHAR) CHECK (stage_key IN ('goal', 'self', 'evaluate', 'review'))   -- ใช้ตรวจกำหนดเวลา (BR-EVAL-03, BR-EVAL-07)
);

-- ตารางที่ 7 evaluation_forms
CREATE TABLE evaluation_forms (
  form_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cycle_id     NUMBER NOT NULL REFERENCES evaluation_cycles(cycle_id),
  form_name    VARCHAR2(100 CHAR) NOT NULL,
  description  CLOB,
  settings     CLOB        -- JSON: ระดับคะแนนและข้อมูลที่ต้องกรอก (UC-13)
);

-- ตารางที่ 8 criteria  (+ category และ sort_order สำหรับจัดหมวดและลำดับข้อ)
CREATE TABLE criteria (
  criteria_id  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  form_id      NUMBER NOT NULL REFERENCES evaluation_forms(form_id),
  title        VARCHAR2(150 CHAR) NOT NULL,
  description  CLOB,
  min_score    NUMBER(5,2) DEFAULT 1 NOT NULL,
  max_score    NUMBER(5,2) DEFAULT 5 NOT NULL,
  category     VARCHAR2(100 CHAR),
  sort_order   NUMBER(3) NOT NULL
);

-- ---------- D2 ข้อมูลเป้าหมาย ----------
-- ตารางที่ 9 goals
CREATE TABLE goals (
  goal_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cycle_id        NUMBER NOT NULL REFERENCES evaluation_cycles(cycle_id),
  employee_id     NUMBER NOT NULL REFERENCES users(user_id),
  title           VARCHAR2(150 CHAR) NOT NULL,
  detail          CLOB,
  status          VARCHAR2(30 CHAR) DEFAULT 'draft' NOT NULL CHECK (status IN ('draft', 'pending_review', 'approved', 'returned')),
  review_comment  CLOB
);

-- ตารางที่ 10 evaluations  (+ strengths, improvements, category_comments, employee_reply, replied_at, updated_at)
-- status ตามภาคผนวก ข: not_started=ยังไม่เริ่ม, draft=ร่าง, pending_mentor=รอพี่เลี้ยงประเมิน, returned=ส่งกลับแก้ไข,
--                      pending_hr=รอ HR ตรวจสอบ, confirmed=ยืนยันแล้ว, published=เผยแพร่ผลแล้ว, acknowledged=รับทราบผลแล้ว
CREATE TABLE evaluations (
  evaluation_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cycle_id             NUMBER NOT NULL REFERENCES evaluation_cycles(cycle_id),
  employee_id          NUMBER NOT NULL REFERENCES users(user_id),
  mentor_id            NUMBER REFERENCES users(user_id),
  form_id              NUMBER NOT NULL REFERENCES evaluation_forms(form_id),
  status               VARCHAR2(30 CHAR) DEFAULT 'not_started' NOT NULL CHECK (status IN
                       ('not_started', 'draft', 'pending_mentor', 'returned', 'pending_hr', 'confirmed', 'published', 'acknowledged')),
  self_submitted_at    TIMESTAMP,
  mentor_submitted_at  TIMESTAMP,
  strengths            CLOB,
  improvements         CLOB,
  category_comments    CLOB,
  employee_reply       VARCHAR2(1300 CHAR),
  replied_at           TIMESTAMP,
  self_comment         CLOB,
  self_category_comments CLOB,
  updated_at           TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uq_evaluations_cycle_emp UNIQUE (cycle_id, employee_id)
);
CREATE INDEX ix_evaluations_status ON evaluations (cycle_id, status);

-- ตารางที่ 11 evaluation_scores  (คอลัมน์ comment ในเอกสารใช้ชื่อ comment_text เพราะ COMMENT เป็นคำสงวนของ Oracle)
CREATE TABLE evaluation_scores (
  score_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  evaluation_id   NUMBER NOT NULL REFERENCES evaluations(evaluation_id),
  criteria_id     NUMBER NOT NULL REFERENCES criteria(criteria_id),
  evaluator_role  VARCHAR2(20 CHAR) NOT NULL CHECK (evaluator_role IN ('employee', 'mentor', 'hr')),
  score           NUMBER(5,2) NOT NULL,
  comment_text    CLOB,
  CONSTRAINT uq_scores UNIQUE (evaluation_id, criteria_id, evaluator_role)
);

-- ตารางที่ 12 return_records
CREATE TABLE return_records (
  return_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  evaluation_id  NUMBER NOT NULL REFERENCES evaluations(evaluation_id),
  reason         CLOB NOT NULL,
  returned_at    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- ---------- D4 ข้อมูลผลการประเมิน ----------
-- ตารางที่ 13 evaluation_results
CREATE TABLE evaluation_results (
  result_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  evaluation_id    NUMBER NOT NULL UNIQUE REFERENCES evaluations(evaluation_id),
  final_score      NUMBER(5,2),
  summary          CLOB,
  confirmed_at     TIMESTAMP,
  published_at     TIMESTAMP,
  acknowledged_at  TIMESTAMP
);

-- ตารางที่ 4 audit_logs
CREATE TABLE audit_logs (
  log_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id       NUMBER REFERENCES users(user_id),
  entity_type    VARCHAR2(50 CHAR) NOT NULL,
  entity_id      NUMBER,
  action         VARCHAR2(30 CHAR) NOT NULL,
  change_detail  CLOB,
  action_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX ix_audit_entity ON audit_logs (entity_type, entity_id);

-- ---------- ตารางเพิ่มเติมของระบบต้นแบบ (ไม่มีในเอกสาร) ----------
-- work_schedules: ตารางเวลางานรายสัปดาห์ DAY_NO 1=จันทร์ ... 7=อาทิตย์, SHIFT_CODE M/A/N/OFF
CREATE TABLE work_schedules (
  user_id     NUMBER NOT NULL REFERENCES users(user_id),
  day_no      NUMBER(1) NOT NULL CHECK (day_no BETWEEN 1 AND 7),
  shift_code  VARCHAR2(10 CHAR) NOT NULL CHECK (shift_code IN ('M', 'A', 'N', 'OFF')),
  updated_at  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_work_schedules PRIMARY KEY (user_id, day_no)
);

-- deadline_extensions: HR อนุมัติให้ส่งหลังกำหนดเวลา (BR-EVAL-07) รายคน รายขั้นตอน
CREATE TABLE deadline_extensions (
  ext_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cycle_id     NUMBER NOT NULL REFERENCES evaluation_cycles(cycle_id),
  employee_id  NUMBER NOT NULL REFERENCES users(user_id),
  stage_key    VARCHAR2(20 CHAR) NOT NULL CHECK (stage_key IN ('goal', 'self', 'evaluate', 'review')),
  until_date   DATE NOT NULL,
  reason       VARCHAR2(500 CHAR),
  granted_by   NUMBER REFERENCES users(user_id),
  granted_at   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uq_deadline_ext UNIQUE (cycle_id, employee_id, stage_key)
);

