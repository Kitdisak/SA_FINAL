CREATE TABLE EVAL_ACCOUNTS (
  USER_ID        VARCHAR2(40)   PRIMARY KEY,
  FULL_NAME      VARCHAR2(150)  NOT NULL,
  ROLE           VARCHAR2(20)   NOT NULL CHECK (ROLE IN ('evaluator', 'evaluatee')),
  POSITION_NAME  VARCHAR2(150),
  PIN_HASH       CHAR(64)       NOT NULL,
  IS_ACTIVE      NUMBER(1)      DEFAULT 1 NOT NULL CHECK (IS_ACTIVE IN (0,1)),
  CREATED_AT     TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE EVAL_EVALUATIONS (
  EVALUATEE_ID   VARCHAR2(40) PRIMARY KEY,
  EVALUATOR_ID   VARCHAR2(40) NOT NULL,
  STATUS         VARCHAR2(20) DEFAULT 'draft' NOT NULL CHECK (STATUS IN ('draft', 'submitted')),
  PAYLOAD        CLOB NOT NULL,
  UPDATED_AT     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT FK_EVAL_EVALUATEE FOREIGN KEY (EVALUATEE_ID) REFERENCES EVAL_ACCOUNTS(USER_ID),
  CONSTRAINT FK_EVAL_EVALUATOR FOREIGN KEY (EVALUATOR_ID) REFERENCES EVAL_ACCOUNTS(USER_ID)
);

