-- 3) ตารางเวลางานรายสัปดาห์ (DAY_NO: 1=จันทร์ ... 7=อาทิตย์)
--    SHIFT_CODE: M=กะเช้า 08:00-17:00, A=กะบ่าย 13:00-22:00, N=กะดึก 22:00-07:00, OFF=วันหยุด
CREATE TABLE EVAL_SCHEDULES (
  USER_ID     VARCHAR2(40) NOT NULL,
  DAY_NO      NUMBER(1)    NOT NULL CHECK (DAY_NO BETWEEN 1 AND 7),
  SHIFT_CODE  VARCHAR2(10) NOT NULL CHECK (SHIFT_CODE IN ('M', 'A', 'N', 'OFF')),
  UPDATED_AT  TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_EVAL_SCHEDULES PRIMARY KEY (USER_ID, DAY_NO),
  CONSTRAINT FK_SCHED_USER FOREIGN KEY (USER_ID) REFERENCES EVAL_ACCOUNTS(USER_ID)
);

-- ตารางเริ่มต้น: จันทร์-ศุกร์ กะเช้า, เสาร์-อาทิตย์ หยุด
INSERT INTO EVAL_SCHEDULES (USER_ID, DAY_NO, SHIFT_CODE)
SELECT a.USER_ID, d.DAY_NO, CASE WHEN d.DAY_NO >= 6 THEN 'OFF' ELSE 'M' END
FROM EVAL_ACCOUNTS a
CROSS JOIN (SELECT LEVEL AS DAY_NO FROM DUAL CONNECT BY LEVEL <= 7) d
WHERE a.ROLE = 'evaluatee';

