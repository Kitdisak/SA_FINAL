-- 4) แจ้งเตือน
CREATE TABLE EVAL_NOTIFICATIONS (
  NOTI_ID     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  USER_ID     VARCHAR2(40)   NOT NULL,
  TITLE       VARCHAR2(200)  NOT NULL,
  BODY        VARCHAR2(1000),
  LINK_VIEW   VARCHAR2(30),
  IS_READ     NUMBER(1)      DEFAULT 0 NOT NULL CHECK (IS_READ IN (0, 1)),
  CREATED_AT  TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT FK_NOTI_USER FOREIGN KEY (USER_ID) REFERENCES EVAL_ACCOUNTS(USER_ID)
);
CREATE INDEX IX_NOTI_USER ON EVAL_NOTIFICATIONS (USER_ID, IS_READ);

